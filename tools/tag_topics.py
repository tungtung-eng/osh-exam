COMMON = {
    "90006": ("C1", "共同：職業安全衛生"),
    "90007": ("C2", "共同：工作倫理與職業道德"),
    "90008": ("C3", "共同：環境保護"),
    "90009": ("C4", "共同：節能減碳"),
}
OTHER = ("T16", "其他綜合")


def main():
    data = json.loads(BANK.read_text(encoding="utf-8"))
    cnt = collections.Counter()
    for q in data["questions"]:
        if q["subj"] in COMMON:
            q["topic"], q["topicName"] = COMMON[q["subj"]]
        else:
            # 題幹優先判斷（選項常常是干擾項），題幹沒中再看選項
            for text in (q["q"], q["q"] + " ".join(q["opts"])):
                hit = next((t for t in TOPICS if re.search(t[2], text)), None)
                if hit:
                    break
            q["topic"], q["topicName"] = (hit[0], hit[1]) if hit else OTHER
        cnt[(q["topic"], q["topicName"])] += 1
    BANK.write_text(json.dumps(data, ensure_ascii=False, indent=0), encoding="utf-8")
    for k, v in sorted(cnt.items()):
        print(k[0], k[1], v)


if __name__ == "__main__":
    main()
